"""Offline parity checks complement (and do not replace) PostgreSQL catalog tests."""

import importlib.util
from io import StringIO
from pathlib import Path
from types import SimpleNamespace

import sqlalchemy as sa
from alembic.config import Config
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex

from alembic import command
from app.models import Base

ROOT = Path(__file__).resolve().parents[1]
DIALECT = postgresql.dialect()


def table_signature(table):
    columns = [
        (
            column.name,
            column.type.compile(dialect=DIALECT),
            column.nullable,
            str(column.server_default.arg)
            if column.server_default and not column.identity
            else None,
            (
                tuple(
                    getattr(column.identity, attribute)
                    for attribute in (
                        "always",
                        "start",
                        "increment",
                        "minvalue",
                        "maxvalue",
                        "cycle",
                        "cache",
                    )
                )
                if column.identity
                else None
            ),
        )
        for column in table.columns
    ]
    constraints = set()
    for constraint in table.constraints:
        detail = tuple(column.name for column in constraint.columns)
        if isinstance(constraint, sa.CheckConstraint):
            detail = str(constraint.sqltext)
        elif isinstance(constraint, sa.ForeignKeyConstraint):
            detail = (
                detail,
                tuple(element.target_fullname for element in constraint.elements),
                constraint.ondelete,
                constraint.onupdate,
            )
        constraints.add((type(constraint).__name__, str(constraint.name), detail))
    return columns, constraints


def test_initial_migration_and_models_have_identical_definitions(monkeypatch):
    specification = importlib.util.spec_from_file_location(
        "initial_migration", ROOT / "alembic/versions/0001_foundation.py"
    )
    migration = importlib.util.module_from_spec(specification)
    specification.loader.exec_module(migration)
    migrated = sa.MetaData()

    def create_table(name, *elements):
        return sa.Table(name, migrated, *elements)

    def create_index(name, table_name, expressions):
        table = migrated.tables[table_name]
        columns = [table.c[e] if isinstance(e, str) else e for e in expressions]
        sa.Index(name, *columns)

    monkeypatch.setattr(
        migration,
        "op",
        SimpleNamespace(create_table=create_table, create_index=create_index, f=lambda name: name),
    )
    migration.upgrade()
    assert set(migrated.tables) == set(Base.metadata.tables) - {"settlements"}
    for name, model_table in Base.metadata.tables.items():
        if name == "settlements":
            continue
        assert table_signature(migrated.tables[name]) == table_signature(model_table)
        assert {
            str(CreateIndex(i).compile(dialect=DIALECT)) for i in migrated.tables[name].indexes
        } == {str(CreateIndex(i).compile(dialect=DIALECT)) for i in model_table.indexes}


def test_alembic_generates_postgresql_ddl_without_database(monkeypatch):
    monkeypatch.setenv("DATABASE_URL", "postgresql+psycopg://demo:demo@localhost/demo")
    output = StringIO()
    config = Config(str(ROOT / "alembic.ini"), output_buffer=output)
    command.upgrade(config, "head", sql=True)
    ddl = output.getvalue()
    assert ddl.count("CREATE TABLE ") == 7  # six application tables plus Alembic's version table
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL" in ddl
    assert "FOREIGN KEY(group_id, paid_by)" in ddl
    assert "REFERENCES group_members (group_id, user_id) ON DELETE RESTRICT" in ddl
    assert "(group_id, created_at DESC, id DESC)" in ddl
